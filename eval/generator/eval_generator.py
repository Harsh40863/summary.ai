# 4. RETRY WRAPPER & GROQ/GROK LLM JUDGE
# ============================================================
def call_with_retries(fn, metrics: GeneratorMetrics):
    """
    Executes an LLM evaluation call with exponential backoff on errors.
    """
    metrics.calls += 1

    for attempt in range(MAX_RETRIES + 1):
        try:
            result = fn()
            metrics.successes += 1
            return result
        except Exception as e:
            if attempt < MAX_RETRIES:
                metrics.retries += 1
                backoff = BACKOFF_BASE_S * (2 ** attempt)
                time.sleep(backoff)
            else:
                metrics.failures += 1
                print(f"  [!] Evaluation call failed after {MAX_RETRIES} retries: {e}")
                return None


class GeneratorLLMJudge:
    """
    Evaluates Generator Precision (Faithfulness) and Recall (Completeness)
    using Groq (fast LPU) or Grok (xAI) via OpenAI-compatible API.
    Falls back gracefully to deterministic keyword/ground-truth matching
    if no API key is provided.
    """

    def __init__(
        self,
        provider: str = DEFAULT_PROVIDER,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        base_url: Optional[str] = None,
    ):
        self.provider = provider.lower()

        if self.provider == "grok":
            self.api_key = api_key or XAI_API_KEY
            self.base_url = base_url or os.getenv("XAI_BASE_URL", "https://api.x.ai/v1")
            self.model = model or os.getenv("GROK_MODEL", "grok-2-latest")
        else:
            self.provider = "groq"
            self.api_key = api_key or GROQ_API_KEY
            self.base_url = base_url or os.getenv("GROQ_BASE_URL", "https://api.groq.com/openai/v1")
            self.model = model or os.getenv("GROQ_MODEL", "qwen/qwen3.8-27b")

        self.client: Optional[OpenAI] = None
        if self.api_key:
            self.client = OpenAI(api_key=self.api_key, base_url=self.base_url)
        else:
            print(f"[INFO] No {self.provider.upper()}_API_KEY found.")
            print(f"       Running with deterministic ground-truth answer matcher.")
            print(f"       To run live with {self.provider.capitalize()}, set {self.provider.upper()}_API_KEY in your .env file.\n")

    def _judge_with_llm(
        self,
        query: str,
        generated_answer: str,
        ideal_answer: str,
        context: str,
        category: str,
    ) -> Dict[str, Any]:
        """Calls Groq/Grok to evaluate precision and recall."""
        assert self.client is not None

        system_prompt = (
            "You are an expert AI evaluator assessing the generation stage of a RAG pipeline.\n"
            "Evaluate two metrics: Answer Precision (Faithfulness) and Answer Recall (Completeness).\n\n"
            "DEFINITIONS:\n"
            "1. ANSWER PRECISION (0.0 to 1.0):\n"
            "   - Measures whether the statements made in the GENERATED ANSWER are factual, correct,\n"
            "     and fully supported by the provided CONTEXT and GROUND TRUTH.\n"
            "   - Penalize hallucinations, contradictions, or unsupported claims.\n"
            "   - If the query is an out-of-domain/negative query and the generated answer correctly states\n"
            "     that no relevant information is available: score is 1.0.\n"
            "   - Otherwise: score = (count of supported statements) / (total statements in generated answer).\n\n"
            "2. ANSWER RECALL (0.0 to 1.0):\n"
            "   - Measures whether all essential facts/claims from the EXPECTED GROUND TRUTH ANSWER are\n"
            "     present in the GENERATED ANSWER.\n"
            "   - Penalize omission of critical figures, names, or key points required by the ground truth.\n"
            "   - If the query is an out-of-domain/negative query (expected: no info) and the generated answer\n"
            "     correctly states no info exists: score is 1.0.\n"
            "   - Otherwise: score = (count of expected facts captured) / (total expected facts in ground truth).\n\n"
            "Respond ONLY with a valid JSON object in this exact schema:\n"
            "{\n"
            '  "precision": <float between 0.0 and 1.0>,\n'
            '  "precision_reason": "<1-2 sentence explanation>",\n'
            '  "recall": <float between 0.0 and 1.0>,\n'
            '  "recall_reason": "<1-2 sentence explanation>"\n'
            "}"
        )

        user_prompt = (
            f"User Query:\n{query}\n\n"
            f"Category: {category}\n\n"
            f"Retrieved Context:\n{context or '(No context retrieved)'}\n\n"
            f"Expected Ground Truth Answer:\n{ideal_answer}\n\n"
            f"Actual Generated Answer:\n{generated_answer}\n"
        )

        response = self.client.chat.completions.create(
            model=self.model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.0,
        )

        raw = response.choices[0].message.content or "{}"
        clean = re.sub(r"^```(?:json)?\s*", "", raw.strip(), flags=re.MULTILINE)
        clean = re.sub(r"```$", "", clean.strip(), flags=re.MULTILINE)

        data = json.loads(clean.strip())
        precision = float(data.get("precision", 0.0))
        recall = float(data.get("recall", 0.0))

        return {
            "precision": max(0.0, min(1.0, precision)),
            "recall": max(0.0, min(1.0, recall)),
            "precision_reason": data.get("precision_reason", ""),
            "recall_reason": data.get("recall_reason", ""),
            "judge": f"{self.provider} ({self.model})",
        }

    def _judge_deterministic(
        self,
        query: str,
        generated_answer: str,
        ideal_answer: str,
        context: str,
        category: str,
    ) -> Dict[str, Any]:
        """Deterministic keyword / fact overlap against ground truth."""
        gen_lower = generated_answer.lower()
        ideal_lower = ideal_answer.lower()

        # Handle negative / out-of-domain query
        if category == "negative_test" or "no relevant information" in ideal_lower:
            negative_indicators = [
                "no relevant information",
                "not available",
                "no information",
                "cannot answer",
                "not found",
                "does not contain",
            ]
            correctly_rejected = any(ind in gen_lower for ind in negative_indicators)
            score = 1.0 if correctly_rejected else 0.0
            reason = (
                "Correctly stated no information is available for out-of-domain query"
                if score == 1.0
                else "Generated response failed to identify lack of document context"
            )
            return {
                "precision": score,
                "recall": score,
                "precision_reason": reason,
                "recall_reason": reason,
                "judge": "ground-truth-match (fallback)",
            }

        # Break ideal answer into key sentences / facts
        ideal_sentences = [
            s.strip() for s in re.split(r"[.!?]", ideal_answer) if len(s.strip()) > 10
        ]
        if not ideal_sentences:
            ideal_sentences = [ideal_answer]

        # Calculate Recall: fraction of ideal facts found in generated answer
        captured_facts = 0
        for sent in ideal_sentences:
            sent_words = set(re.findall(r"\w+", sent.lower()))
            gen_words = set(re.findall(r"\w+", gen_lower))
            overlap = len(sent_words & gen_words)
            if overlap / max(1, len(sent_words)) >= 0.5:
                captured_facts += 1

        recall = captured_facts / len(ideal_sentences)

        # Calculate Precision: fraction of generated answer grounded in context / ideal
        gen_sentences = [
            s.strip() for s in re.split(r"[.!?]", generated_answer) if len(s.strip()) > 10
        ]
        if not gen_sentences:
            gen_sentences = [generated_answer]

        grounded_claims = 0
        source_text = (context + " " + ideal_answer).lower()
        source_words = set(re.findall(r"\w+", source_text))

        for sent in gen_sentences:
            sent_words = set(re.findall(r"\w+", sent.lower()))
            overlap = len(sent_words & source_words)
            if overlap / max(1, len(sent_words)) >= 0.5:
                grounded_claims += 1

        precision = grounded_claims / len(gen_sentences)

        return {
            "precision": max(0.0, min(1.0, precision)),
            "recall": max(0.0, min(1.0, recall)),
            "precision_reason": f"{grounded_claims}/{len(gen_sentences)} statements grounded in document context",
            "recall_reason": f"{captured_facts}/{len(ideal_sentences)} key reference facts captured in answer",
            "judge": "ground-truth-match (fallback)",
        }

    def evaluate(
        self,
        query: str,
        generated_answer: str,
        ideal_answer: str,
        context: str,
        category: str,
    ) -> Dict[str, Any]:
        if self.client is not None:
            return self._judge_with_llm(
                query, generated_answer, ideal_answer, context, category
            )
        return self._judge_deterministic(
            query, generated_answer, ideal_answer, context, category
        )


