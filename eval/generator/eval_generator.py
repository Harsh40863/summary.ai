"""
Generator eval: CONTEXTUAL PRECISION & RECALL (with Groq / Grok as LLM Judge)

Precision and Recall measure the accuracy, faithfulness, and completeness
of answers generated by the summary.ai RAG pipeline against the golden dataset:

We measure:
    - Answer Precision (Faithfulness): Proportion of claims in the generated
      answer that are factually grounded and supported by the context / ground truth
      (measures freedom from hallucinations).
    - Answer Recall (Coverage / Completeness): Proportion of essential facts from
      the golden reference answer captured in the generated answer.
    - F1 Score: Harmonic mean of Answer Precision and Answer Recall.
    - Pass Rate: Percentage of cases meeting the pass threshold for both metrics.

Evaluated against the golden dataset (eval/datasets/retriever_golden_dataset.json)
using Groq (Llama-3.3-70b / Llama-3.1-8b) or Grok (xAI) as the LLM judge
with automatic retry handling and exponential backoff.
"""

