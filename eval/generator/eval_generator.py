# 5. BENCHMARK
# ============================================================
def benchmark(
    golden_path: Path = DEFAULT_GOLDEN_PATH,
    threshold: float = DEFAULT_THRESHOLD,
    category: Optional[str] = None,
    skip_negative: bool = False,
    judge: Optional[GeneratorLLMJudge] = None,
) -> GeneratorMetrics:

    if judge is None:
        judge = GeneratorLLMJudge()

    goldens = load_goldens(golden_path)
    if category:
        goldens = [g for g in goldens if g.get("category") == category]
    if skip_negative:
        goldens = [g for g in goldens if g.get("category") != "negative_test"]

    if not goldens:
        raise ValueError("No golden test cases matched the selected criteria.")

    metrics = GeneratorMetrics(threshold=threshold)
    judge_name = f"{judge.provider} ({judge.model})" if judge.client else "deterministic ground-truth"
    print(f"Measuring generator performance across {len(goldens)} golden cases...")
    print(f"Judge: {judge_name} | Pass Threshold: {threshold:.2f}\n")

    for idx, golden in enumerate(goldens, 1):
        case_id = golden["id"]
        cat = golden.get("category", "general")
        query = golden["query"]
        ideal_answer = golden.get("ideal_answer", "")

        # 1. Generate answer via summary.ai RAG pipeline
        start_time = time.time()
        rag_generator = generator_for_golden(golden)
        generated_answer, retrieved_chunks = rag_generator.invoke(query)
        elapsed_s = time.time() - start_time
        context = "\n\n".join(retrieved_chunks)

        # 2. Evaluate with retry wrapper
        eval_data = call_with_retries(
            lambda: judge.evaluate(
                query=query,
                generated_answer=generated_answer,
                ideal_answer=ideal_answer,
                context=context,
                category=cat,
            ),
            metrics,
        )

        if eval_data is None:
            prec, rec = 0.0, 0.0
            prec_reason = "Evaluation failed after retries"
            rec_reason = "Evaluation failed after retries"
            judge_used = "error"
        else:
            prec = eval_data["precision"]
            rec = eval_data["recall"]
            prec_reason = eval_data["precision_reason"]
            rec_reason = eval_data["recall_reason"]
            judge_used = eval_data.get("judge", judge.provider)

        f1 = (2 * prec * rec / (prec + rec)) if (prec + rec) > 0 else 0.0
        passed = (prec >= threshold) and (rec >= threshold)

        status_icon = "✓" if passed else "✗"
        print(
            f"  {status_icon} [{idx:02d}/{len(goldens):02d}] {case_id} ({cat}): "
            f"Precision={prec:.2f}, Recall={rec:.2f}, F1={f1:.2f} ({elapsed_s:.2f}s)"
        )

        metrics.record_case({
            "id": case_id,
            "category": cat,
            "query": query,
            "generated_answer": generated_answer,
            "ideal_answer": ideal_answer,
            "precision": prec,
            "recall": rec,
            "f1": f1,
            "passed": passed,
            "precision_reason": prec_reason,
            "recall_reason": rec_reason,
            "latency_s": round(elapsed_s, 3),
            "judge": judge_used,
        })

    return metrics


